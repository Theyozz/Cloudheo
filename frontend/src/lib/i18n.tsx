export type TranslationKey = keyof (typeof translations)["en"];

type LanguageContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  // Always render "en" during SSR/first paint so server and client markup
  // match, then sync from localStorage (an external system) once mounted.
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "fr") {
      // eslint-disable-next-line react-hooks/set-state-in-effect -- syncing initial state from localStorage, an external system, on mount
      setLangState(stored);
    }
  }, []);

  function setLang(next: Lang) {
    setLangState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  function t(key: TranslationKey, vars?: Record<string, string | number>) {
    let str: string = translations[lang][key];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        str = str.replace(`{${name}}`, String(value));
      }
    }
    return str;
  }

  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within a LanguageProvider");
  return ctx;
}

/** Both translations size the same grid cell; only the chosen one is visible
 * and accessible. This avoids guessed heights and reflow when switching. */
export function LocalizedText({ id, accentId }: { id: TranslationKey; accentId?: TranslationKey }) {
  const { lang } = useLanguage();

  return (
    <span className="localized-text">
      {(["en", "fr"] as const).map((locale) => (
        <span key={locale} lang={locale} aria-hidden={locale !== lang ? true : undefined}>
          {translations[locale][id]}
          {accentId && <><br /><span className="localized-accent">{translations[locale][accentId]}</span></>}
        </span>
      ))}
    </span>
  );
}
